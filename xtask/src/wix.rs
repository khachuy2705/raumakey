//! WiX v4 source for the x64 MSI.

use std::path::Path;

use raumakey_model::identity::{INSTALLER_UPGRADE_CODE, PRODUCT_NAME};

use crate::targets::Profile;

/// Files of the x64 package that the MSI installs (package-relative, `/` separators). The
/// install scripts, README, and checksum files belong to the zip-style package only.
pub const MSI_FILES: [&str; 6] = [
    "raumakey.exe",
    "x64/raumakey_tip.dll",
    "x86/raumakey_tip.dll",
    "tools/raumakey-test-runner.exe",
    "LICENSE",
    "THIRD_PARTY.md",
];

/// File name of the generated WiX source.
pub fn wxs_file_name(profile: Profile) -> &'static str {
    if profile.is_release() {
        "raumakey.wxs"
    } else {
        "raumakey-debug.wxs"
    }
}

/// File name of the MSI built from the x64 package.
pub fn msi_file_name(version: &str, profile: Profile) -> String {
    let suffix = if profile.is_release() { "" } else { "-debug" };
    format!("raumakey-{version}-windows-x64{suffix}.msi")
}

/// MSI `ProductVersion` for a Cargo version: the numeric `major.minor.patch` part.
pub fn msi_version(version: &str) -> String {
    version
        .split(['-', '+'])
        .next()
        .unwrap_or(version)
        .to_owned()
}

/// Escapes text for an XML attribute value.
pub fn xml_escape(text: &str) -> String {
    let mut escaped = String::with_capacity(text.len());
    for character in text.chars() {
        match character {
            '&' => escaped.push_str("&amp;"),
            '<' => escaped.push_str("&lt;"),
            '>' => escaped.push_str("&gt;"),
            '"' => escaped.push_str("&quot;"),
            '\'' => escaped.push_str("&apos;"),
            other => escaped.push(other),
        }
    }
    escaped
}

/// WiX identifier of the `File` element for a package-relative path.
fn file_id(path: &str) -> String {
    let body: String = path
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '.' || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    format!("F_{body}")
}

/// WiX identifier of the `Directory` that holds a package-relative path.
fn directory_id(path: &str) -> String {
    match path.split_once('/') {
        Some((directory, _)) => format!("DIR_{directory}"),
        None => "INSTALLFOLDER".to_owned(),
    }
}

/// WiX source installing the x64 package layout per machine under
/// `ProgramFiles64Folder\Raumakey`, registering through deferred elevated custom actions.
pub fn wix_source(version: &str, package_dir: &Path) -> String {
    let upgrade_code = INSTALLER_UPGRADE_CODE.to_string();
    let controller = file_id("raumakey.exe");
    let package_dir = package_dir.display().to_string();
    let mut subdirectories: Vec<&str> = Vec::new();
    for path in MSI_FILES {
        if let Some((directory, _)) = path.split_once('/')
            && !subdirectories.contains(&directory)
        {
            subdirectories.push(directory);
        }
    }

    let mut xml = String::new();
    xml.push_str("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    xml.push_str(
        "<!-- Generated by `cargo xtask package`; do not edit. Build: wix build -arch x64 -->\n",
    );
    xml.push_str("<Wix xmlns=\"http://wixtoolset.org/schemas/v4/wxs\">\n");
    xml.push_str(&format!(
        "  <Package Name=\"{PRODUCT_NAME}\" Manufacturer=\"Raumakey contributors\" \
         Version=\"{}\" UpgradeCode=\"{upgrade_code}\" Scope=\"perMachine\" \
         Compressed=\"yes\">\n",
        xml_escape(&msi_version(version))
    ));
    xml.push_str("    <SummaryInformation Description=\"Raumakey Vietnamese input method\" />\n");
    xml.push_str(
        "    <MajorUpgrade DowngradeErrorMessage=\"A newer version of Raumakey is already \
         installed.\" />\n",
    );
    xml.push_str("    <MediaTemplate EmbedCab=\"yes\" />\n\n");

    xml.push_str("    <StandardDirectory Id=\"ProgramFiles64Folder\">\n");
    xml.push_str(&format!(
        "      <Directory Id=\"INSTALLFOLDER\" Name=\"{PRODUCT_NAME}\">\n"
    ));
    for directory in &subdirectories {
        xml.push_str(&format!(
            "        <Directory Id=\"DIR_{directory}\" Name=\"{directory}\" />\n"
        ));
    }
    xml.push_str("      </Directory>\n    </StandardDirectory>\n\n");

    xml.push_str("    <ComponentGroup Id=\"RaumakeyFiles\">\n");
    for path in MSI_FILES {
        let source = format!("{package_dir}\\{}", path.replace('/', "\\"));
        xml.push_str(&format!(
            "      <Component Directory=\"{}\">\n        <File Id=\"{}\" Source=\"{}\" \
             KeyPath=\"yes\" />\n      </Component>\n",
            directory_id(path),
            file_id(path),
            xml_escape(&source)
        ));
    }
    xml.push_str("    </ComponentGroup>\n\n");
    xml.push_str("    <Feature Id=\"Main\" Title=\"Raumakey\" Level=\"1\">\n");
    xml.push_str("      <ComponentGroupRef Id=\"RaumakeyFiles\" />\n    </Feature>\n\n");

    let install = xml_escape(
        "install --tip-x64 \"[DIR_x64]raumakey_tip.dll\" --tip-x86 \"[DIR_x86]raumakey_tip.dll\"",
    );
    let not_removing = xml_escape("NOT (REMOVE~=\"ALL\")");
    let removing = xml_escape("REMOVE~=\"ALL\"");
    xml.push_str(
        "    <!-- Registration runs deferred and elevated (Impersonate=no) through \
         raumakey.exe. -->\n",
    );
    xml.push_str(&format!(
        "    <CustomAction Id=\"RaumakeyRegisterRollback\" FileRef=\"{controller}\" \
         ExeCommand=\"uninstall\" Execute=\"rollback\" Impersonate=\"no\" Return=\"ignore\" />\n"
    ));
    xml.push_str(&format!(
        "    <CustomAction Id=\"RaumakeyRegister\" FileRef=\"{controller}\" \
         ExeCommand=\"{install}\" Execute=\"deferred\" Impersonate=\"no\" Return=\"check\" />\n"
    ));
    xml.push_str(&format!(
        "    <CustomAction Id=\"RaumakeyUnregister\" FileRef=\"{controller}\" \
         ExeCommand=\"uninstall\" Execute=\"deferred\" Impersonate=\"no\" Return=\"ignore\" />\n\n"
    ));
    xml.push_str("    <InstallExecuteSequence>\n");
    xml.push_str(&format!(
        "      <Custom Action=\"RaumakeyRegisterRollback\" After=\"InstallFiles\" \
         Condition=\"{not_removing}\" />\n"
    ));
    xml.push_str(&format!(
        "      <Custom Action=\"RaumakeyRegister\" After=\"RaumakeyRegisterRollback\" \
         Condition=\"{not_removing}\" />\n"
    ));
    xml.push_str(&format!(
        "      <Custom Action=\"RaumakeyUnregister\" Before=\"RemoveFiles\" \
         Condition=\"{removing}\" />\n"
    ));
    xml.push_str("    </InstallExecuteSequence>\n  </Package>\n</Wix>\n");
    xml
}

/// Arguments for `wix build`.
pub fn wix_build_args(wxs: &Path, msi: &Path) -> Vec<String> {
    vec![
        "build".to_owned(),
        "-arch".to_owned(),
        "x64".to_owned(),
        "-o".to_owned(),
        msi.display().to_string(),
        wxs.display().to_string(),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    const PACKAGE_DIR: &str = r"C:\out & co\raumakey-0.1.0-windows-x64";

    /// Minimal well-formedness check: balanced tags and only predefined entities.
    fn assert_well_formed(xml: &str) {
        let mut stack: Vec<String> = Vec::new();
        let mut rest = xml;
        while let Some(start) = rest.find('<') {
            let end = start + rest[start..].find('>').expect("unterminated tag");
            let tag = &rest[start + 1..end];
            rest = &rest[end + 1..];
            if tag.starts_with('?') {
                continue;
            }
            if let Some(comment) = tag.strip_prefix("!--") {
                assert!(comment.ends_with("--"), "comment {tag}");
                assert!(!comment[..comment.len() - 2].contains("--"), "{tag}");
                continue;
            }
            if let Some(name) = tag.strip_prefix('/') {
                assert_eq!(stack.pop().as_deref(), Some(name.trim()), "closing {name}");
                continue;
            }
            let name = tag
                .split_whitespace()
                .next()
                .expect("tag name")
                .trim_end_matches('/')
                .to_owned();
            if !tag.ends_with('/') {
                stack.push(name);
            }
        }
        assert!(stack.is_empty(), "unclosed {stack:?}");
        for (index, _) in xml.match_indices('&') {
            let entity = &xml[index..];
            assert!(
                ["&amp;", "&quot;", "&lt;", "&gt;", "&apos;"]
                    .iter()
                    .any(|known| entity.starts_with(known)),
                "bad entity at {}",
                &xml[index..index + 8]
            );
        }
    }

    #[test]
    fn names_and_versions() {
        assert_eq!(wxs_file_name(Profile::Release), "raumakey.wxs");
        assert_eq!(wxs_file_name(Profile::Debug), "raumakey-debug.wxs");
        assert_eq!(
            msi_file_name("0.1.0", Profile::Release),
            "raumakey-0.1.0-windows-x64.msi"
        );
        assert_eq!(
            msi_file_name("0.1.0", Profile::Debug),
            "raumakey-0.1.0-windows-x64-debug.msi"
        );
        assert_eq!(msi_version("0.1.0"), "0.1.0");
        assert_eq!(msi_version("1.2.3-rc.1"), "1.2.3");
        assert_eq!(msi_version("1.2.3+build.7"), "1.2.3");
    }

    #[test]
    fn xml_escaping() {
        assert_eq!(
            xml_escape(r#"a&b<c>d"e'f"#),
            "a&amp;b&lt;c&gt;d&quot;e&apos;f"
        );
        assert_eq!(xml_escape("plain"), "plain");
    }

    #[test]
    fn source_is_a_well_formed_v4_per_machine_package() {
        let xml = wix_source("0.1.0-rc.1", Path::new(PACKAGE_DIR));
        assert!(xml.starts_with("<?xml version=\"1.0\" encoding=\"utf-8\"?>"));
        assert_well_formed(&xml);
        for needle in [
            r#"<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">"#,
            r#"Name="Raumakey""#,
            r#"Version="0.1.0""#,
            r#"UpgradeCode="{BF73893F-FCEB-4BAE-AE1C-E81D7107ECE5}""#,
            r#"Scope="perMachine""#,
            "<MajorUpgrade ",
            r#"<MediaTemplate EmbedCab="yes" />"#,
            r#"<StandardDirectory Id="ProgramFiles64Folder">"#,
            r#"<Directory Id="INSTALLFOLDER" Name="Raumakey">"#,
            r#"<Directory Id="DIR_x64" Name="x64" />"#,
            r#"<Directory Id="DIR_x86" Name="x86" />"#,
            r#"<Directory Id="DIR_tools" Name="tools" />"#,
            r#"<ComponentGroupRef Id="RaumakeyFiles" />"#,
        ] {
            assert!(xml.contains(needle), "WiX source lacks {needle}\n{xml}");
        }
    }

    #[test]
    fn every_msi_file_is_installed_from_the_package_directory() {
        let xml = wix_source("0.1.0", Path::new(PACKAGE_DIR));
        let escaped_dir = r"C:\out &amp; co\raumakey-0.1.0-windows-x64";
        for (file, directory, id) in [
            ("raumakey.exe", "INSTALLFOLDER", "F_raumakey.exe"),
            ("x64\\raumakey_tip.dll", "DIR_x64", "F_x64_raumakey_tip.dll"),
            ("x86\\raumakey_tip.dll", "DIR_x86", "F_x86_raumakey_tip.dll"),
            (
                "tools\\raumakey-test-runner.exe",
                "DIR_tools",
                "F_tools_raumakey_test_runner.exe",
            ),
            ("LICENSE", "INSTALLFOLDER", "F_LICENSE"),
            ("THIRD_PARTY.md", "INSTALLFOLDER", "F_THIRD_PARTY.md"),
        ] {
            let component = format!(
                "<Component Directory=\"{directory}\">\n        <File Id=\"{id}\" \
                 Source=\"{escaped_dir}\\{file}\" KeyPath=\"yes\" />\n      </Component>"
            );
            assert!(xml.contains(&component), "missing {component}\n{xml}");
        }
        assert!(!xml.contains("install.ps1"));
        assert!(!xml.contains("SHA256SUMS"));
    }

    #[test]
    fn registration_runs_as_deferred_elevated_custom_actions() {
        let xml = wix_source("0.1.0", Path::new(PACKAGE_DIR));
        for needle in [
            r#"<CustomAction Id="RaumakeyRegister" FileRef="F_raumakey.exe" ExeCommand="install --tip-x64 &quot;[DIR_x64]raumakey_tip.dll&quot; --tip-x86 &quot;[DIR_x86]raumakey_tip.dll&quot;" Execute="deferred" Impersonate="no" Return="check" />"#,
            r#"<CustomAction Id="RaumakeyRegisterRollback" FileRef="F_raumakey.exe" ExeCommand="uninstall" Execute="rollback" Impersonate="no" Return="ignore" />"#,
            r#"<CustomAction Id="RaumakeyUnregister" FileRef="F_raumakey.exe" ExeCommand="uninstall" Execute="deferred" Impersonate="no" Return="ignore" />"#,
            r#"<Custom Action="RaumakeyRegisterRollback" After="InstallFiles" Condition="NOT (REMOVE~=&quot;ALL&quot;)" />"#,
            r#"<Custom Action="RaumakeyRegister" After="RaumakeyRegisterRollback" Condition="NOT (REMOVE~=&quot;ALL&quot;)" />"#,
            r#"<Custom Action="RaumakeyUnregister" Before="RemoveFiles" Condition="REMOVE~=&quot;ALL&quot;" />"#,
        ] {
            assert!(xml.contains(needle), "WiX source lacks {needle}\n{xml}");
        }
    }

    #[test]
    fn build_arguments() {
        assert_eq!(
            wix_build_args(Path::new("raumakey.wxs"), Path::new("raumakey.msi")),
            [
                "build",
                "-arch",
                "x64",
                "-o",
                "raumakey.msi",
                "raumakey.wxs"
            ]
        );
    }
}
