//! `cargo xtask notices`: third-party packages and their licenses for the Windows targets.

use std::collections::{BTreeMap, BTreeSet};

use crate::cargo::Metadata;
use crate::targets::Target;

/// A third-party package of the resolved graph.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Notice {
    /// Package name.
    pub name: String,
    /// Package version.
    pub version: String,
    /// SPDX license expression.
    pub license: Option<String>,
    /// License file declared instead of an expression.
    pub license_file: Option<String>,
    /// Targets whose resolved graph contains the package, in canonical order.
    pub targets: Vec<Target>,
}

impl Notice {
    /// Whether the package declares a license expression.
    pub fn has_license(&self) -> bool {
        self.license
            .as_deref()
            .is_some_and(|license| !license.trim().is_empty())
    }
}

/// Collects every non-workspace package of the per-target resolved graphs, sorted by name and
/// version.
pub fn collect(per_target: &[(Target, Metadata)]) -> Vec<Notice> {
    let mut notices: BTreeMap<(String, String), Notice> = BTreeMap::new();
    for (target, metadata) in per_target {
        let resolved: Option<BTreeSet<&str>> = metadata
            .resolve
            .as_ref()
            .map(|resolve| resolve.nodes.iter().map(|node| node.id.as_str()).collect());
        for package in &metadata.packages {
            let in_graph = resolved
                .as_ref()
                .is_none_or(|ids| ids.contains(package.id.as_str()));
            if !in_graph || metadata.is_workspace_member(&package.id) {
                continue;
            }
            let notice = notices
                .entry((package.name.clone(), package.version.clone()))
                .or_insert_with(|| Notice {
                    name: package.name.clone(),
                    version: package.version.clone(),
                    license: package.license.clone(),
                    license_file: package.license_file.clone(),
                    targets: Vec::new(),
                });
            if !notice.targets.contains(target) {
                notice.targets.push(*target);
            }
        }
    }
    let mut notices: Vec<Notice> = notices.into_values().collect();
    for notice in &mut notices {
        notice.targets.sort();
    }
    notices
}

/// Markdown license list.
pub fn render_markdown(notices: &[Notice]) -> String {
    let triples: Vec<&str> = Target::ALL.iter().map(|target| target.triple()).collect();
    let mut text = String::from("# Third-party crates\n\n");
    text.push_str(&format!(
        "Generated by `cargo xtask notices` from `cargo metadata` for {}.\n\
         Lists every non-workspace package in the resolved graph (normal, build, and \
         development dependencies).\n\n",
        triples.join(", ")
    ));
    text.push_str("| Crate | Version | License | Targets |\n|---|---|---|---|\n");
    for notice in notices {
        let license = if notice.has_license() {
            notice.license.clone().unwrap_or_default()
        } else {
            match &notice.license_file {
                Some(file) => format!("MISSING (license file: {file})"),
                None => "MISSING".to_owned(),
            }
        };
        let targets: Vec<&str> = notice.targets.iter().map(|target| target.arch()).collect();
        text.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            cell(&notice.name),
            cell(&notice.version),
            cell(&license),
            targets.join(", ")
        ));
    }
    text.push_str(&format!("\n{} packages.\n", notices.len()));
    text
}

/// Short summary: package count and license expression histogram.
pub fn summary(notices: &[Notice]) -> String {
    let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
    for notice in notices.iter().filter(|notice| notice.has_license()) {
        *counts
            .entry(notice.license.as_deref().unwrap_or_default())
            .or_default() += 1;
    }
    let mut histogram: Vec<(&str, usize)> = counts.into_iter().collect();
    histogram.sort_by(|left, right| right.1.cmp(&left.1).then(left.0.cmp(right.0)));
    let licenses: Vec<String> = histogram
        .iter()
        .map(|(license, count)| format!("{license} ({count})"))
        .collect();
    let missing: Vec<String> = notices
        .iter()
        .filter(|notice| !notice.has_license())
        .map(|notice| format!("{} {}", notice.name, notice.version))
        .collect();
    let mut text = format!(
        "{} third-party packages; licenses: {}",
        notices.len(),
        licenses.join(", ")
    );
    if !missing.is_empty() {
        text.push_str(&format!(
            "; {} without a license expression: {}",
            missing.len(),
            missing.join(", ")
        ));
    }
    text
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn metadata(packages: &[(&str, &str, Option<&str>)], resolved: &[&str]) -> Metadata {
        let packages: Vec<serde_json::Value> = packages
            .iter()
            .map(|(name, version, license)| {
                serde_json::json!({
                    "name": name,
                    "version": version,
                    "id": format!("{name}@{version}"),
                    "license": license,
                    "license_file": if license.is_none() { Some("LICENSE.txt") } else { None },
                    "targets": [],
                })
            })
            .collect();
        let nodes: Vec<serde_json::Value> = resolved
            .iter()
            .map(|id| serde_json::json!({ "id": id, "deps": [] }))
            .collect();
        let document = serde_json::json!({
            "packages": packages,
            "workspace_members": ["raumakey-model@0.1.0"],
            "target_directory": "target",
            "resolve": { "nodes": nodes, "root": null },
        });
        Metadata::parse(&document.to_string()).expect("metadata parses")
    }

    fn sample() -> Vec<(Target, Metadata)> {
        let x64 = metadata(
            &[
                ("raumakey-model", "0.1.0", Some("GPL-3.0-or-later")),
                ("serde", "1.0.229", Some("MIT OR Apache-2.0")),
                ("windows_x86_64_msvc", "0.53.0", Some("MIT OR Apache-2.0")),
                ("unresolved", "1.0.0", Some("MIT")),
            ],
            &[
                "raumakey-model@0.1.0",
                "serde@1.0.229",
                "windows_x86_64_msvc@0.53.0",
            ],
        );
        let arm64 = metadata(
            &[
                ("raumakey-model", "0.1.0", Some("GPL-3.0-or-later")),
                ("serde", "1.0.229", Some("MIT OR Apache-2.0")),
                ("mystery", "0.0.1", None),
                ("pipes", "2.0.0", Some("MIT|Apache")),
            ],
            &[
                "raumakey-model@0.1.0",
                "serde@1.0.229",
                "mystery@0.0.1",
                "pipes@2.0.0",
            ],
        );
        vec![(Target::X86_64, x64), (Target::Aarch64, arm64)]
    }

    #[test]
    fn collects_the_union_of_resolved_third_party_packages() {
        let notices = collect(&sample());
        let names: Vec<&str> = notices.iter().map(|notice| notice.name.as_str()).collect();
        assert_eq!(names, ["mystery", "pipes", "serde", "windows_x86_64_msvc"]);
        assert_eq!(notices[2].targets, [Target::X86_64, Target::Aarch64]);
        assert_eq!(notices[3].targets, [Target::X86_64]);
        assert_eq!(notices[2].license.as_deref(), Some("MIT OR Apache-2.0"));
        assert!(!notices[0].has_license());
        assert_eq!(notices[0].license_file.as_deref(), Some("LICENSE.txt"));
        assert!(notices[2].has_license());
    }

    #[test]
    fn blank_license_expressions_count_as_missing() {
        let notice = Notice {
            name: "blank".to_owned(),
            version: "1.0.0".to_owned(),
            license: Some("  ".to_owned()),
            license_file: None,
            targets: vec![Target::I686],
        };
        assert!(!notice.has_license());
    }

    #[test]
    fn markdown_lists_every_package_with_targets() {
        let markdown = render_markdown(&collect(&sample()));
        assert!(markdown.starts_with("# Third-party crates\n"));
        assert!(markdown.contains("| Crate | Version | License | Targets |"));
        assert!(markdown.contains("| serde | 1.0.229 | MIT OR Apache-2.0 | x64, arm64 |"));
        assert!(markdown.contains("| windows_x86_64_msvc | 0.53.0 | MIT OR Apache-2.0 | x64 |"));
        assert!(
            markdown.contains("| mystery | 0.0.1 | MISSING (license file: LICENSE.txt) | arm64 |")
        );
        assert!(markdown.contains("| pipes | 2.0.0 | MIT\\|Apache | arm64 |"));
        assert!(markdown.contains("x86_64-pc-windows-msvc"));
        assert!(!markdown.contains("raumakey-model"));
        assert!(!markdown.contains("unresolved"));
    }

    #[test]
    fn summary_counts_packages_and_licenses() {
        let text = summary(&collect(&sample()));
        assert!(text.contains("4 third-party packages"), "{text}");
        assert!(text.contains("MIT OR Apache-2.0 (2)"), "{text}");
        assert!(text.contains("MIT|Apache (1)"), "{text}");
        assert!(
            text.contains("1 without a license expression: mystery 0.0.1"),
            "{text}"
        );
    }
}
