#[derive(Serialize)]
struct Manifest<'a> {
    product: &'static str,
    version: &'a str,
    arch: &'static str,
    profile: &'static str,
    signed: bool,
    runtime_verified: bool,
    compile_gated: bool,
    files: &'a [ManifestFile],
}

/// `manifest.json` describing a package.
pub fn manifest_json(
    kind: PackageKind,
    version: &str,
    profile: Profile,
    files: &[ManifestFile],
) -> Result<String> {
    let manifest = Manifest {
        product: PRODUCT_NAME,
        version,
        arch: kind.arch(),
        profile: profile.dir_name(),
        signed: false,
        runtime_verified: false,
        compile_gated: kind.compile_gated(),
        files,
    };
    let mut text = serde_json::to_string_pretty(&manifest)?;
    text.push('\n');
    Ok(text)
}

fn crlf(text: &str) -> String {
    text.replace("\r\n", "\n").replace('\n', "\r\n")
}

/// Inputs for assembling a package on disk.
#[derive(Clone, Copy, Debug)]
pub struct PackageInputs<'a> {
    /// Repository root (source of `LICENSE` and `THIRD_PARTY.md`).
    pub repo_root: &'a Path,
    /// Cargo target directory holding the cross-built artifacts.
    pub target_dir: &'a Path,
    /// Product version.
    pub version: &'a str,
    /// Profile of the packaged artifacts.
    pub profile: Profile,
}

/// A package written to disk.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AssembledPackage {
    /// Package directory.
    pub dir: PathBuf,
    /// Every file written, including `manifest.json` and `SHA256SUMS`.
    pub files: Vec<PathBuf>,
}

/// Source files of a package that do not exist (cross-built artifacts or repository files).
pub fn missing_inputs(kind: PackageKind, inputs: &PackageInputs<'_>) -> Vec<PathBuf> {
    package_files(kind, inputs.version, inputs.profile)
        .iter()
        .filter_map(|file| source_path(&file.source, inputs))
        .filter(|path| !path.is_file())
        .collect()
}

/// Location of a non-generated source.
fn source_path(source: &FileSource, inputs: &PackageInputs<'_>) -> Option<PathBuf> {
    match source {
        FileSource::Artifact(artifact, target) => {
            Some(artifact.path(inputs.target_dir, *target, inputs.profile))
        }
        FileSource::Repository(file) => Some(inputs.repo_root.join(file)),
        FileSource::Generated(_) => None,
    }
}

/// Error for missing package inputs, telling which `cross` invocation produces them.
pub fn missing_inputs_error(profile: Profile, missing: &[PathBuf]) -> Error {
    let list: Vec<String> = missing
        .iter()
        .map(|path| format!("  {}", path.display()))
        .collect();
    Error::new(format!(
        "missing package inputs:\n{}\nRun `{}` first.",
        list.join("\n"),
        profile.cross_command()
    ))
}

/// Writes a fresh package directory below `out_dir`: payload files, `manifest.json` (payload sizes
/// and digests), and `SHA256SUMS` (every file except itself).
pub fn assemble(
    kind: PackageKind,
    inputs: &PackageInputs<'_>,
    out_dir: &Path,
) -> Result<AssembledPackage> {
    let missing = missing_inputs(kind, inputs);
    if !missing.is_empty() {
        return Err(missing_inputs_error(inputs.profile, &missing));
    }
    let files = package_files(kind, inputs.version, inputs.profile);
    let dir = out_dir.join(package_dir_name(kind, inputs.version, inputs.profile));
    if dir.exists() {
        fs::remove_dir_all(&dir).map_err(|error| Error::io("remove", &dir, error))?;
    }
    let mut written = Vec::new();
    let mut manifest_files = Vec::new();
    for file in &files {
        let destination = file
            .path
            .split('/')
            .fold(dir.clone(), |path, part| path.join(part));
        if let Some(parent) = destination.parent() {
            fs::create_dir_all(parent).map_err(|error| Error::io("create", parent, error))?;
        }
        match (&file.source, source_path(&file.source, inputs)) {
            (FileSource::Generated(text), _) => fs::write(&destination, text)
                .map_err(|error| Error::io("write", &destination, error))?,
            (_, Some(source)) => {
                fs::copy(&source, &destination)
                    .map_err(|error| Error::io("copy", &source, error))?;
            }
            (_, None) => return Err(Error::new(format!("no source for {}", file.path))),
        }
        manifest_files.push(ManifestFile {
            path: file.path.to_owned(),
            size: fs::metadata(&destination)
                .map_err(|error| Error::io("stat", &destination, error))?
                .len(),
            sha256: sha256_file(&destination)
                .map_err(|error| Error::io("hash", &destination, error))?,
            target: match file.source {
                FileSource::Artifact(_, target) => Some(target.triple()),
                _ => None,
            },
        });
        written.push(destination);
    }

    let manifest_path = dir.join(MANIFEST);
    let manifest = manifest_json(kind, inputs.version, inputs.profile, &manifest_files)?;
    fs::write(&manifest_path, &manifest)
        .map_err(|error| Error::io("write", &manifest_path, error))?;
    let mut sums: Vec<(String, String)> = manifest_files
        .iter()
        .map(|file| (file.path.clone(), file.sha256.clone()))
        .collect();
    sums.push((MANIFEST.to_owned(), sha256_hex(manifest.as_bytes())));
    written.push(manifest_path);
    let sums_path = dir.join(SHA256SUMS);
    fs::write(&sums_path, format_sha256sums(&sums))
        .map_err(|error| Error::io("write", &sums_path, error))?;
    written.push(sums_path);
    Ok(AssembledPackage {
        dir,
        files: written,
    })
}

