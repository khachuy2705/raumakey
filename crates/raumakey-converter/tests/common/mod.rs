/// Windows-1252 0x80..=0x9F as published (undefined bytes shown as C1 controls).
pub const CP1252_80_9F: [char; 32] = [
    '€', '\u{81}', '‚', 'ƒ', '„', '…', '†', '‡', 'ˆ', '‰', 'Š', '‹', 'Œ', '\u{8D}', 'Ž', '\u{8F}',
    '\u{90}', '‘', '’', '“', '”', '•', '–', '—', '˜', '™', 'š', '›', 'œ', '\u{9D}', 'ž', 'Ÿ',
];

/// The Windows-1252 text form of legacy bytes (how they appear on the clipboard).
pub fn cp1252(bytes: &[u8]) -> String {
    bytes
        .iter()
        .map(|&byte| match byte {
            0x80..=0x9F => CP1252_80_9F[usize::from(byte - 0x80)],
            _ => char::from(byte),
        })
        .collect()
}

/// The bytes behind a Windows-1252 text form (inverse of [`cp1252`]).
pub fn cp1252_bytes(text: &str) -> Vec<u8> {
    text.chars()
        .map(|c| {
            if let Some(offset) = CP1252_80_9F.iter().position(|&entry| entry == c) {
                0x80 + u8::try_from(offset).unwrap()
            } else {
                u8::try_from(c).expect("not a Windows-1252 character")
            }
        })
        .collect()
}

/// The 134 letters as a vector of characters.
